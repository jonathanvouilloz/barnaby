export const dictionaries: Record<Lang, Record<string, string>> = { fr, en };

/** Pure lookup: language, then French, then the key itself. */
export function translate(lang: Lang, key: string, params?: Params): string {
  const s = dictionaries[lang]?.[key] ?? fr[key] ?? key;
  return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m)) : s;
}

// The UI binds a reactive object here, so `t` re-renders when the language changes.
let locale: { lang: Lang } = { lang: 'fr' };
export function bindLocale(source: { lang: Lang }) {
  locale = source;
}

export function t(key: string, params?: Params): string {
  return translate(locale.lang, key, params);
}

export function has(key: string): boolean {
  return key in fr;
}
